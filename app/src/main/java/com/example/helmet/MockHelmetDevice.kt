package com.example.helmet

import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.Job
import kotlinx.coroutines.delay
import kotlinx.coroutines.launch
import java.util.UUID

/**
 * Test/mock command representing an unsupported or unrecognized command type,
 * used to verify graceful handling without crashing.
 */
data class MockUnsupportedCommand(
  override val commandId: String = UUID.randomUUID().toString()
) : HelmetCommand

/**
 * Mock smart helmet device simulating the embedded hardware and firmware of a RideAware helmet.
 * Used for testing RideAware's connection, command dispatch, telemetry ingestion, and error recovery
 * in a software-only environment without real Bluetooth LE / Classic hardware.
 *
 * All connections, telemetry, and events generated by this class are clearly identified as DEMO / SIMULATED.
 */
class MockHelmetDevice(
  val communicator: SimulatedHelmetCommunicator,
  private val scope: CoroutineScope = CoroutineScope(Dispatchers.Default),
  val deviceId: String = DEFAULT_DEMO_DEVICE_ID,
  val deviceName: String = DEFAULT_DEMO_DEVICE_NAME
) {
  companion object {
    const val DEFAULT_DEMO_DEVICE_ID = "DEMO-HELMET-01"
    const val DEFAULT_DEMO_DEVICE_NAME = "DEMO / SIMULATED Geni Smart Helmet"
    const val DEFAULT_SERIAL_NUMBER = "DEMO-SN-8820"
    const val DEFAULT_FIRMWARE_VERSION = "v2.4.1-DEMO"
    const val DEFAULT_HARDWARE_REVISION = "Rev 3-SIMULATED"
  }

  private var commandListenerJob: Job? = null
  private var batteryPercent: Int = 88
  private var isCharging: Boolean = false
  private var activeLedPattern: LedPattern = LedPattern.OFF
  private var bootTimestampMillis: Long = System.currentTimeMillis()

  // Diagnostic tracking for test assertions
  private val _receivedCommands = mutableListOf<HelmetCommand>()
  val receivedCommands: List<HelmetCommand>
    get() = synchronized(_receivedCommands) { _receivedCommands.toList() }

  private val _dispatchedAcks = mutableListOf<HelmetMessage.CommandAck>()
  val dispatchedAcks: List<HelmetMessage.CommandAck>
    get() = synchronized(_dispatchedAcks) { _dispatchedAcks.toList() }

  init {
    communicator.directCommandListener = { command ->
      processInboundCommand(command)
    }
    startListeningToCommandStream()
  }

  private fun startListeningToCommandStream() {
    commandListenerJob?.cancel()
    commandListenerJob = scope.launch {
      communicator.commandStream.collect { command ->
        // directCommandListener already processed it if set;
        // if directCommandListener wasn't used or was null, process here.
        if (communicator.directCommandListener == null) {
          processInboundCommand(command)
        }
      }
    }
  }

  /**
   * Process a command sent from RideAware to the mock helmet device.
   * Dispatches typed command acknowledgements and reacts with appropriate mock state changes
   * or response messages.
   * Handles invalid or unsupported commands safely without crashing.
   */
  fun processInboundCommand(command: HelmetCommand) {
    synchronized(_receivedCommands) {
      _receivedCommands.add(command)
    }

    try {
      when (command) {
        is HelmetCommand.Ping -> {
          val ack = HelmetMessage.CommandAck(
            targetCommandId = command.commandId,
            success = true
          )
          recordAndDispatchAck(ack)
          // Also return a heartbeat telemetry message
          communicator.simulateInboundMessage(
            HelmetMessage.Heartbeat(
              uptimeSeconds = ((System.currentTimeMillis() - bootTimestampMillis) / 1000L).coerceAtLeast(1L)
            )
          )
        }

        is HelmetCommand.RequestBattery -> {
          val ack = HelmetMessage.CommandAck(
            targetCommandId = command.commandId,
            success = true
          )
          recordAndDispatchAck(ack)
          // Reply with current battery telemetry
          communicator.simulateInboundMessage(
            HelmetMessage.BatteryLevel(
              percent = batteryPercent,
              isCharging = isCharging
            )
          )
        }

        is HelmetCommand.RequestDeviceInfo -> {
          val ack = HelmetMessage.CommandAck(
            targetCommandId = command.commandId,
            success = true
          )
          recordAndDispatchAck(ack)
          communicator.simulateInboundMessage(
            HelmetMessage.DeviceInfo(
              serialNumber = DEFAULT_SERIAL_NUMBER,
              firmwareVersion = DEFAULT_FIRMWARE_VERSION,
              hardwareRevision = DEFAULT_HARDWARE_REVISION
            )
          )
        }

        is HelmetCommand.SetLedPattern -> {
          activeLedPattern = command.pattern
          val ack = HelmetMessage.CommandAck(
            targetCommandId = command.commandId,
            success = true
          )
          recordAndDispatchAck(ack)
          communicator.simulateInboundMessage(
            HelmetMessage.LedStatus(
              pattern = command.pattern,
              active = command.pattern != LedPattern.OFF
            )
          )
        }

        is HelmetCommand.TriggerHapticFeedback -> {
          val ack = HelmetMessage.CommandAck(
            targetCommandId = command.commandId,
            success = true
          )
          recordAndDispatchAck(ack)
        }

        is HelmetCommand.Disconnect -> {
          val ack = HelmetMessage.CommandAck(
            targetCommandId = command.commandId,
            success = true
          )
          recordAndDispatchAck(ack)
          communicator.disconnect()
        }

        else -> {
          // Unsupported or unknown command type: handle safely without crashing
          val ack = HelmetMessage.CommandAck(
            targetCommandId = command.commandId,
            success = false,
            errorMessage = "DEMO / SIMULATED: Command ${command::class.simpleName ?: "Unknown"} is unsupported by mock firmware."
          )
          recordAndDispatchAck(ack)
        }
      }
    } catch (e: Exception) {
      // Safe error containment
      val ack = HelmetMessage.CommandAck(
        targetCommandId = command.commandId,
        success = false,
        errorMessage = "DEMO / SIMULATED: Failed to process command: ${e.message}"
      )
      recordAndDispatchAck(ack)
    }
  }

  private fun recordAndDispatchAck(ack: HelmetMessage.CommandAck) {
    synchronized(_dispatchedAcks) {
      _dispatchedAcks.add(ack)
    }
    communicator.simulateInboundMessage(ack)
  }

  /**
   * Simulates initiating connection with optional simulated connection delay.
   */
  fun connectDemo(delayMillis: Long = 0L, autoSendTelemetry: Boolean = true) {
    communicator.simulateConnecting(deviceId, attempt = 1)
    if (delayMillis > 0L) {
      scope.launch {
        delay(delayMillis)
        completeConnection(autoSendTelemetry)
      }
    } else {
      completeConnection(autoSendTelemetry)
    }
  }

  fun completeConnection(autoSendTelemetry: Boolean = true) {
    communicator.simulateConnectionSuccess(
      deviceId = deviceId,
      deviceName = deviceName
    )
    if (autoSendTelemetry) {
      // Send initial battery and device info telemetry
      sendBatteryLevel(batteryPercent, isCharging)
      sendDeviceInfo()
    }
  }

  fun disconnectDemo() {
    communicator.disconnect()
  }

  fun simulateConnectionError(
    reason: String = "DEMO / SIMULATED: Bluetooth link dropped",
    recoverable: Boolean = true
  ) {
    communicator.simulateError(message = reason, recoverable = recoverable)
  }

  fun recoverConnection(autoSendTelemetry: Boolean = true) {
    connectDemo(delayMillis = 0L, autoSendTelemetry = autoSendTelemetry)
  }

  fun sendBatteryLevel(percent: Int, isCharging: Boolean = false) {
    this.batteryPercent = percent.coerceIn(0, 100)
    this.isCharging = isCharging
    communicator.simulateInboundMessage(
      HelmetMessage.BatteryLevel(
        percent = this.batteryPercent,
        isCharging = this.isCharging
      )
    )
  }

  fun sendButtonEvent(button: HelmetButton, action: ButtonAction = ButtonAction.PRESS) {
    communicator.simulateInboundMessage(
      HelmetMessage.ButtonEvent(
        button = button,
        action = action
      )
    )
  }

  fun sendHeartbeat(uptimeSeconds: Long? = null) {
    val uptime = uptimeSeconds ?: ((System.currentTimeMillis() - bootTimestampMillis) / 1000L).coerceAtLeast(1L)
    communicator.simulateInboundMessage(
      HelmetMessage.Heartbeat(uptimeSeconds = uptime)
    )
  }

  fun sendDeviceInfo(
    serialNumber: String = DEFAULT_SERIAL_NUMBER,
    firmwareVersion: String = DEFAULT_FIRMWARE_VERSION,
    hardwareRevision: String = DEFAULT_HARDWARE_REVISION
  ) {
    communicator.simulateInboundMessage(
      HelmetMessage.DeviceInfo(
        serialNumber = serialNumber,
        firmwareVersion = firmwareVersion,
        hardwareRevision = hardwareRevision
      )
    )
  }

  /**
   * Safely process raw or untyped data packets without crashing.
   */
  fun handleRawPacketSafely(rawPacket: ByteArray?): Boolean {
    if (rawPacket == null || rawPacket.isEmpty()) {
      return false
    }
    return try {
      val packetText = String(rawPacket, Charsets.UTF_8)
      if (packetText.contains("PING", ignoreCase = true)) {
        communicator.simulateInboundMessage(HelmetMessage.Heartbeat(uptimeSeconds = 1L))
      }
      true
    } catch (_: Exception) {
      false
    }
  }

  fun clearHistory() {
    synchronized(_receivedCommands) { _receivedCommands.clear() }
    synchronized(_dispatchedAcks) { _dispatchedAcks.clear() }
  }
}
